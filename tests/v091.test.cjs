'use strict';
const assert=require('node:assert/strict');
const {defaultProps}=require('../web/engine.js');
const {simulateSpice}=require('../web/spice.js');
const n=(id,type,props={})=>({id,type,x:0,y:0,label:id,props:{...defaultProps(type),...props}});
const w=(from,fromPin,to,toPin)=>({from,fromPin,to,toPin,input:0});
const s=n('s','VDC',{voltage:5}),d=n('d','LED_GREEN'),r=n('r','RESISTOR',{resistance:220});
const sim=(nodes,wires)=>simulateSpice(nodes,wires,1);
const a=sim([s,r,d],[w('s',1,'r',0),w('r',1,'d',0),w('d',1,'s',0)]);
assert.ok(a.readings.get('d').current>.008&&a.readings.get('d').current<.02);assert.equal(a.fault,false);
const b=sim([s,r,d],[w('r',0,'s',1),w('d',0,'r',1),w('s',0,'d',1)]);
assert.ok(Math.abs(a.readings.get('d').current-b.readings.get('d').current)<1e-7);
const c=sim([s,d],[w('s',0,'d',0),w('d',1,'s',1)]);
assert.ok(Math.abs(c.readings.get('d').current)<1e-6);assert.match(c.warnings.join(' '),/polaridad/);
const e=sim([s,d],[w('s',1,'d',0),w('d',1,'s',0)]);
assert.ok(e.readings.get('d').current>.03);assert.equal(e.fault,true);assert.match(e.warnings.join(' '),/resistencia en serie/);
const f=sim([s,d],[w('s',1,'d',0)]);assert.ok(Math.abs(f.readings.get('d').current)<1e-5);
const g=sim([s,n('a','LED_GREEN'),n('b','LED_WHITE')],[w('s',1,'a',0),w('s',1,'b',0),w('a',1,'s',0),w('b',1,'s',0)]);
assert.ok(g.readings.get('a').supported&&g.readings.get('b').supported);
const fs=require('node:fs');const app=fs.readFileSync(require('node:path').join(__dirname,'../web/app.js'),'utf8');
assert.match(app,/function analogWireFlow/);assert.match(app,/flow<0\?wirePath\(ptB,ptA\)/);
console.log('PASS 7 pruebas de regresión Patiñ Os v0.9.1');
