'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname,'..');
const read = p => fs.readFileSync(path.join(root,p),'utf8');
const gradle=read('app/build.gradle');
const release=read('.github/workflows/release-signed.yml');
const ci=read('.github/workflows/android-apk.yml');
assert.match(gradle,/versionCode\s+18/);
assert.match(gradle,/versionName\s+'1\.0\.0'/);
assert.match(read('web/index.html'),/v1\.0\.0/);
assert.equal(read('web/index.html'),read('app/src/main/assets/index.html'));
assert.match(release,/github\.event\.repository\.private/);
assert.match(release,/PATINOS_KEYSTORE_BASE64/);
assert.match(release,/apksigner/);
assert.match(release,/gh release create v1\.0\.0/);
assert.doesNotMatch(ci,/gh release create/);
console.log('PASS version 1.0.0 / private signed release protections');
